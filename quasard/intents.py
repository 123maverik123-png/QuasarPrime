"""Локальные команды, которые выполняем без LLM (быстро и надёжно)."""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from .protocol import client_action

_NUMS = {
    "ноль": 0, "один": 1, "одна": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5,
    "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10, "максимум": 10, "минимум": 1,
}


@dataclass
class IntentResult:
    text: str = ""  # что сказать (пусто — молча)
    directives: list[dict] = field(default_factory=list)
    reset_dialog: bool = False


def _norm(text: str) -> str:
    return " ".join(re.sub(r"[^\w\s]", " ", text.lower().replace("ё", "е")).split())


def _level(words: list[str]) -> int | None:
    for w in words:
        if w.isdigit():
            return int(w)
        if w in _NUMS:
            return _NUMS[w]
    return None


def match(text: str) -> IntentResult | None:
    t = _norm(text)
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", t)
    words = t.split()
    if not words:
        return None

    if re.fullmatch(r"(стоп|хватит|замолчи|молчи|отмена|тихо|выключись|помолчи)( пожалуйста)?", t):
        return IntentResult()

    if re.search(r"\b(громкость|уровень громкости|поставь громкость|сделай громкость)\b", t):
        lvl = _level(words)
        if lvl is not None and 0 <= lvl <= 10:
            return IntentResult(directives=[client_action("sound_set_level",
                                                          {"new_level": lvl, "new_percent_level": lvl * 10})])
    _what = r"( музыку| музыка| звук| песню| трек)?"
    if re.fullmatch(rf"(сделай|сделать|можно)?{_what} ?(погромче|громче|прибавь|увеличь громкость|еще громче)"
                    rf"{_what}( пожалуйста)?", t):
        return IntentResult(directives=[client_action("sound_louder")])
    if re.fullmatch(rf"(сделай|сделать|можно)?{_what} ?(потише|тише|убавь|уменьши громкость|еще тише)"
                    rf"{_what}( пожалуйста)?", t):
        return IntentResult(directives=[client_action("sound_quiter")])  # именно quiter — так у Яндекса

    if re.search(r"\b(включи|запусти)\b.*\b(блютуз|bluetooth)\b", t):
        return IntentResult("Включаю блютуз.", [client_action("start_bluetooth")])
    if re.search(r"\b(выключи|отключи)\b.*\b(блютуз|bluetooth)\b", t):
        return IntentResult("Выключаю блютуз.", [client_action("stop_bluetooth")])

    if re.fullmatch(r"(давай )?(начнем сначала|новый (диалог|разговор)|забудь (все|наш разговор)|сбрось (диалог|контекст))", t):
        return IntentResult("Хорошо, начнём заново.", reset_dialog=True)
    return None


# ------------------------------------------------------- внешний YouTube-плеер
#
# Короткие команды управления потоком, который играет quasard-youtube.
# Вызывать ТОЛЬКО когда этот поток активен: иначе «следующая» должна уйти
# встроенной Яндекс.Музыке (а «пауза» — её же player_pause).

# «продолжай», «продолжи воспроизведение песни», «возобнови», «сними с паузы»,
# «включи обратно», «играй дальше», «давай дальше», «продолжи с того же места».
# Объект после глагола необязателен и может повторяться — иначе живая фраза вида
# «продолжай воспроизведение песни» не распознаётся и улетает в LLM (а тот ищет
# новый трек вместо снятия с паузы).
# Голое «играй» считается продолжением: пока YouTube-сессия активна, это
# «продолжай», а не «включи музыку» (проверка активности — на вызывающей стороне).
_RESUME_OBJECT = (
    r"(?:воспроизведение|воспроизведения|проигрывание|проигрывания"
    r"|музыку|музычку|музыки|песню|песни|песня|трек|трека|треки|композицию|композиции"
    r"|этот|эту|это|этого|этому|этом|ее"
    r"|петь|играть|слушать"
    r"|дальше|снова|опять|то же|с того же места|с этого места)"
)
_RESUME_VERB = (
    r"(?:продолж\w*|возобнов\w*|давай дальше|дальше играй|можешь продолж\w*"
    r"|сним\w* (?:это )?с паузы|сня(?:ть|л) паузу|убери паузу|включи обратно)"
)
_RESUME = (
    r"(?:"
    r"(?:" + _RESUME_VERB + r")"
    r"(?: " + _RESUME_OBJECT + r")*"
    r"|играй(?: " + _RESUME_OBJECT + r")*"
    r")"
    r"(?: пожалуйста)?"
)

_YOUTUBE_COMMANDS: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "pause",
        re.compile(
            r"(пауза|на паузу|поставь( это)? на паузу|приостанови( музыку| трек| воспроизведение)?"
            r"|останови( музыку| трек| воспроизведение)?|выключи музыку)( пожалуйста)?"
        ),
    ),
    (
        "resume",
        # «играй»/«играй дальше» тоже считается продолжением — но только пока
        # сессия YouTube активна (проверка на вызывающей стороне).
        re.compile(rf"(?:{_RESUME}|играй(?: {_RESUME_OBJECT})*)"),
    ),
    (
        "next",
        re.compile(
            r"(дальше|следующ\w*( трек| песня| песню)?|пропусти\w*|пропускай|некст"
            r"|переключи( трек| песню| на следующ\w+)?|другую( песню| музыку)?"
            r"|включи следующ\w+( трек| песню)?)( пожалуйста)?"
        ),
    ),
)


def match_youtube(text: str) -> str | None:
    """Короткая команда внешнему плееру: ``pause`` / ``resume`` / ``next``.

    Возвращает ``None``, если фраза не является командой плеера. Проверка
    «а YouTube ли сейчас играет» — на вызывающей стороне.
    """
    t = re.sub(r"^(алиса|слушай алиса)\s+", "", _norm(text))
    if not t or len(t.split()) > 8:
        # 8 слов, а не 5: живые фразы вроде «продолжай воспроизведение песни
        # с того же места» длиннее, а паттерны и так заякорены fullmatch-ом.
        return None
    for action, pattern in _YOUTUBE_COMMANDS:
        if pattern.fullmatch(t):
            return action
    return None


