"""Файл куки для yt-dlp: --cookies появляется только когда он пригоден.

Каталог для файлов — рядом с тестами (как в test_config.py), а не pytest
tmp_path: так тесты одинаково работают и в ограниченном окружении, где
системный %TEMP% недоступен.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from quasard_youtube.config import Config, load_config
from quasard_youtube.cookies import inspect_cookies, js_solver_status
from quasard_youtube.youtube import TrackInfo, YoutubeResolver, _extra_args_use_cookies

_HEADER = "# Netscape HTTP Cookie File\n"
_WORK = Path(__file__).with_name("_tmp_cookies")
_ROOT = Path(__file__).resolve().parent.parent


@pytest.fixture
def workdir(monkeypatch: pytest.MonkeyPatch) -> Path:
    """Изолированный каталог: и конфиг, и cwd, чтобы не поймать живой cookies.txt."""
    shutil.rmtree(_WORK, ignore_errors=True)
    _WORK.mkdir(parents=True, exist_ok=True)
    monkeypatch.chdir(_WORK)
    yield _WORK
    monkeypatch.chdir(_ROOT)
    shutil.rmtree(_WORK, ignore_errors=True)


def _netscape(*rows: tuple[str, str, str]) -> str:
    """Собрать Netscape-файл: строки (домен, имя, значение)."""
    lines = [_HEADER]
    for domain, name, value in rows:
        lines.append(f"{domain}\tTRUE\t/\tTRUE\t1893456000\t{name}\t{value}\n")
    return "".join(lines)


def _authorized_cookies() -> str:
    return _netscape(
        (".youtube.com", "SID", "g.a000xyz"),
        (".youtube.com", "HSID", "AVvAbc"),
        (".youtube.com", "LOGIN_INFO", "AFmmFA"),
        (".google.com", "NID", "511"),
    )


def _config(workdir: Path, *, cookies: str) -> Config:
    """Конфиг через TOML, как у пользователя: config_path важен для путей."""
    path = workdir / "config.toml"
    path.write_text(f'[youtube]\ncookies_file = "{cookies}"\n', encoding="utf-8")
    return load_config(path)


def _resolver(config: Config) -> YoutubeResolver:
    try:
        return YoutubeResolver(config)
    except Exception as exc:  # noqa: BLE001 - yt-dlp может отсутствовать
        pytest.skip(f"yt-dlp недоступен: {exc}")


def _track() -> TrackInfo:
    return TrackInfo(
        video_id="dQw4w9WgXcQ",
        title="t",
        artist="a",
        duration=214.0,
        webpage_url="https://www.youtube.com/watch?v=dQw4w9WgXcQ",
    )


def test_no_flag_without_file(workdir: Path) -> None:
    resolver = _resolver(_config(workdir, cookies="cookies.txt"))
    assert resolver.cookies_file is None
    assert "--cookies" not in resolver._base_args()


def test_empty_setting_disables_cookies(workdir: Path) -> None:
    (workdir / "cookies.txt").write_text(_authorized_cookies(), encoding="utf-8")
    resolver = _resolver(_config(workdir, cookies=""))
    assert resolver.cookies_file is None
    assert "--cookies" not in resolver._base_args()


def test_flag_added_when_file_exists(workdir: Path) -> None:
    cookies = workdir / "cookies.txt"
    cookies.write_text(_authorized_cookies(), encoding="utf-8")
    resolver = _resolver(_config(workdir, cookies="cookies.txt"))

    jar = workdir / "cookies.work.txt"
    assert resolver.cookies_source == cookies.resolve()
    assert resolver.cookies_file == jar
    assert jar.is_file()
    args = resolver._base_args()
    assert args.count("--cookies") == 1
    assert args[args.index("--cookies") + 1] == str(jar)


def test_source_export_is_never_modified(workdir: Path) -> None:
    """yt-dlp перезаписывает --cookies, поэтому ему достаётся копия."""
    cookies = workdir / "cookies.txt"
    original = _authorized_cookies()
    cookies.write_text(original, encoding="utf-8")
    resolver = _resolver(_config(workdir, cookies="cookies.txt"))

    # Имитируем yt-dlp: он сохраняет банку в переданный файл.
    assert resolver.cookies_file is not None
    resolver.cookies_file.write_text(
        "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.\n",
        encoding="utf-8",
    )
    assert cookies.read_text(encoding="utf-8") == original


def test_working_copy_refreshed_after_reexport(workdir: Path) -> None:
    cookies = workdir / "cookies.txt"
    cookies.write_text(_netscape((".youtube.com", "PREF", "a")), encoding="utf-8")
    first = _resolver(_config(workdir, cookies="cookies.txt"))
    assert first.cookies_file is not None
    stale = first.cookies_file.read_text(encoding="utf-8")
    assert "SID" not in stale

    cookies.write_text(_authorized_cookies(), encoding="utf-8")
    second = _resolver(_config(workdir, cookies="cookies.txt"))
    assert second.cookies_file is not None
    assert "SID" in second.cookies_file.read_text(encoding="utf-8")


def test_flag_goes_to_both_search_and_stream(workdir: Path) -> None:
    (workdir / "cookies.txt").write_text(_authorized_cookies(), encoding="utf-8")
    resolver = _resolver(_config(workdir, cookies="cookies.txt"))
    jar = workdir / "cookies.work.txt"

    stream = resolver.stream_args(_track())
    assert stream[stream.index("--cookies") + 1] == str(jar)
    # Поиск и стрим собираются из одного _base_args — флаг общий.
    assert resolver._base_args().count("--cookies") == 1


def test_json_export_is_ignored(workdir: Path) -> None:
    (workdir / "cookies.txt").write_text(
        '[{"domain": ".youtube.com", "name": "SID", "value": "x"}]', encoding="utf-8"
    )
    resolver = _resolver(_config(workdir, cookies="cookies.txt"))
    assert resolver.cookies_file is None
    assert "--cookies" not in resolver._base_args()


def test_netscape_without_header_is_ignored(workdir: Path) -> None:
    path = workdir / "cookies.txt"
    path.write_text(
        ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tSID\tx\n", encoding="utf-8"
    )
    report = inspect_cookies(path)
    assert report.exists and not report.valid
    assert "Netscape" in report.detail
    assert _resolver(_config(workdir, cookies="cookies.txt")).cookies_file is None


def test_foreign_domain_is_ignored(workdir: Path) -> None:
    (workdir / "cookies.txt").write_text(
        _netscape((".example.com", "sid", "1")), encoding="utf-8"
    )
    assert _resolver(_config(workdir, cookies="cookies.txt")).cookies_file is None


def test_http_only_prefix_is_parsed_and_anonymous_detected(workdir: Path) -> None:
    path = workdir / "cookies.txt"
    path.write_text(
        _HEADER
        + "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1893456000\tPREF\ttz=UTC\n"
        + ".youtube.com\tTRUE\t/\tTRUE\t1893456000\tYSC\tabc\n",
        encoding="utf-8",
    )
    report = inspect_cookies(path)
    assert report.valid
    assert report.entries == 2
    assert report.youtube_entries == 2
    assert not report.authorized


def test_absolute_path_and_env_substitution(
    workdir: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    cookies = workdir / "secret" / "cookies.txt"
    cookies.parent.mkdir()
    cookies.write_text(_authorized_cookies(), encoding="utf-8")
    monkeypatch.setenv("MY_COOKIES", str(cookies))
    config = _config(workdir, cookies="${MY_COOKIES}")
    assert config.resolve_cookies_file() == cookies.resolve()


def test_relative_path_falls_back_to_cwd(
    workdir: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """config.toml может лежать в другом месте, чем cookies.txt."""
    config_dir = workdir / "cfg"
    config_dir.mkdir()
    (config_dir / "config.toml").write_text(
        '[youtube]\ncookies_file = "cookies.txt"\n', encoding="utf-8"
    )
    (workdir / "cookies.txt").write_text(_authorized_cookies(), encoding="utf-8")
    monkeypatch.chdir(workdir)
    config = load_config(config_dir / "config.toml")
    assert config.resolve_cookies_file() == (workdir / "cookies.txt").resolve()


def test_file_added_after_start_is_picked_up(workdir: Path) -> None:
    """Файл положили после запуска сервиса — подхватываем без рестарта."""
    resolver = _resolver(_config(workdir, cookies="cookies.txt"))
    assert resolver.cookies_file is None

    (workdir / "cookies.txt").write_text(_authorized_cookies(), encoding="utf-8")
    args = resolver._base_args()

    assert resolver.cookies_file == workdir / "cookies.work.txt"
    assert args[args.index("--cookies") + 1] == str(workdir / "cookies.work.txt")


def test_extra_args_cookies_is_respected(workdir: Path) -> None:
    (workdir / "cookies.txt").write_text(_authorized_cookies(), encoding="utf-8")
    path = workdir / "config.toml"
    path.write_text(
        '[youtube]\ncookies_file = "cookies.txt"\n'
        'extra_args = ["--cookies-from-browser", "firefox"]\n',
        encoding="utf-8",
    )
    resolver = _resolver(load_config(path))
    assert resolver.cookies_file is None
    assert resolver._base_args().count("--cookies") == 0


@pytest.mark.parametrize(
    "args, expected",
    [
        ([], False),
        (["--proxy", "http://127.0.0.1:8080"], False),
        (["--cookies", "/tmp/c.txt"], True),
        (["--cookies=/tmp/c.txt"], True),
        (["--cookies-from-browser", "chrome"], True),
        (["--cookies-from-browser=chrome:Default"], True),
    ],
)
def test_extra_args_detector(args: list[str], expected: bool) -> None:
    assert _extra_args_use_cookies(args) is expected


def test_public_dict_exposes_cookies_setting(workdir: Path) -> None:
    config = _config(workdir, cookies="cookies.txt")
    assert config.public_dict()["youtube"]["cookies_file"] == "cookies.txt"


# --- JS-солвер: без него с куки YouTube не отдаёт аудио -------------------


def _patch_solver(
    monkeypatch: pytest.MonkeyPatch,
    *,
    ejs: bool,
    which: dict[str, str | None],
) -> None:
    monkeypatch.setattr(
        "quasard_youtube.cookies.importlib.util.find_spec",
        lambda name: object() if (ejs and name == "yt_dlp_ejs") else None,
    )
    monkeypatch.setattr(
        "quasard_youtube.cookies.shutil.which", lambda name: which.get(name)
    )


def test_solver_missing_package(monkeypatch: pytest.MonkeyPatch) -> None:
    _patch_solver(monkeypatch, ejs=False, which={"deno": "deno.exe"})
    ready, detail = js_solver_status([])
    assert not ready
    assert "yt-dlp-ejs" in detail


def test_solver_deno_is_default_runtime(monkeypatch: pytest.MonkeyPatch) -> None:
    _patch_solver(monkeypatch, ejs=True, which={"deno": r"C:\deno\deno.exe"})
    ready, detail = js_solver_status([])
    assert ready
    assert "deno" in detail


def test_solver_node_needs_explicit_flag(monkeypatch: pytest.MonkeyPatch) -> None:
    _patch_solver(monkeypatch, ejs=True, which={"node": r"C:\Program Files\nodejs\node.exe"})
    ready, detail = js_solver_status([])
    assert not ready
    assert "node" in detail and "--js-runtimes" in detail

    ready, detail = js_solver_status(["--js-runtimes", "node"])
    assert ready
    assert "node" in detail


def test_solver_explicit_path_must_exist(
    monkeypatch: pytest.MonkeyPatch, workdir: Path
) -> None:
    _patch_solver(monkeypatch, ejs=True, which={})
    assert not js_solver_status(["--js-runtimes", r"node:C:\nope\node.exe"])[0]

    real = workdir / "node.exe"
    real.write_text("", encoding="utf-8")
    assert js_solver_status(["--js-runtimes", f"node:{real}"])[0]


def test_solver_accepts_equals_form(monkeypatch: pytest.MonkeyPatch) -> None:
    _patch_solver(monkeypatch, ejs=True, which={"node": "node.exe"})
    assert js_solver_status(["--js-runtimes=node"])[0]
